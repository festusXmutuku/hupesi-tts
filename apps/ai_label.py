"""Mark "AI-generated" audio files exported by the app (machine-readable metadata tags).

The Artificial Intelligence Law (effective 2026-03-01) requires AI-generated audio to be
labeled in a machine-readable format. Metadata tags are the cheapest approach: WAV gets
LIST/INFO chunks (ICMT, ISFT), and MP3 gets ID3 tags (COMM, TSSE) via libsndfile's LAME
encoder - no extra libraries needed. Tags do not change the audio; anyone who edits the
file in other software may remove the tags, which is a limitation of this approach
(an embedded audio watermark would require torch).

Use ASCII only: WAV INFO chunks and ID3 tags written by LAME are Latin-1, so accented
Vietnamese characters would become garbled in tag readers.
"""
from __future__ import annotations

from apps.app_version import APP_VERSION

# The app name is also included in the comment: for MP3, LAME overwrites the software tag with its own name.
AI_COMMENT = "AI-generated speech (text-to-speech), Hupesi TTS. Voice generated by AI."
SOFTWARE = f"Hupesi TTS {APP_VERSION}"


HEADER = "X-AI-Generated"


class AiHeaderMiddleware:
    """Attach the ``X-AI-Generated: true`` header to every ``audio/*`` response.

    ``/stream`` must keep a plain 44-byte WAV header (the client trims exactly 44 bytes),
    so it cannot carry in-file tags; the HTTP header is the machine-readable marker for it,
    and is applied to all other audio responses for consistency. Implemented as plain ASGI
    middleware instead of ``@app.middleware("http")``: Starlette's BaseHTTPMiddleware breaks
    ``request.is_disconnected()``, which the Stop button relies on."""

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)

        async def send_with_header(message):
            if message["type"] == "http.response.start":
                headers = list(message.get("headers", []))
                ctype = next((v for k, v in headers if k.lower() == b"content-type"), b"")
                if ctype.lower().startswith(b"audio/"):
                    headers.append((HEADER.lower().encode(), b"true"))
                    message = {**message, "headers": headers}
            await send(message)

        await self.app(scope, receive, send_with_header)


def label(sound_file) -> None:
    """Attach tags to a ``soundfile.SoundFile`` just opened for WRITING, before writing any samples:
    the MP3 encoder writes the ID3 tag at the start, so setting it later loses it. Formats that do
    not support tags are skipped - this never breaks audio export."""
    for name, value in (("comment", AI_COMMENT), ("software", SOFTWARE)):
        try:
            setattr(sound_file, name, value)
        except Exception:
            pass
